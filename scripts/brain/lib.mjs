// Shared helpers for the brain scripts.
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

export const ROOT = new URL("../../", import.meta.url).pathname;
export const EVIDENCE_DIR = join(ROOT, "content/brain/evidence");
export const DRAFTS_DIR = join(ROOT, "brain-inbox/drafts");

export const jsonFiles = (dir) => {
  try {
    return readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
  } catch {
    return [];
  }
};

export const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));

// Generated index.ts content: stable and sorted.
export function renderIndex(files) {
  const names = files.map((f) => f.replace(/\.json$/, "")).sort();
  const ident = (n) => n.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : "")).replace(/^(\d)/, "_$1");
  const imports = names.map((n) => `import ${ident(n)} from "./${n}.json";`).join("\n");
  const spread = names.map((n) => `...(${ident(n)} as Evidence[])`).join(", ");
  return [
    "// GENERATED by scripts/brain/gen-index.mjs. Do not edit by hand; run `npm run brain:index`.",
    "// Every evidence file in this folder, as one array.",
    'import type { Evidence } from "../../../src/lib/ask/types";',
    imports,
    "",
    `export const evidence: Evidence[] = [${spread}];`,
    "",
  ].join("\n");
}
